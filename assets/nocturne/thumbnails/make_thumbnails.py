#!/usr/bin/env python3
"""Generate the theme thumbnail SVGs in this directory.

Original vector artwork for Typewriter Nocturne (MIT). Colours mirror the design tokens in
lib/nocturne/themes.ts. Run with plain Python 3 (no dependencies); CI renders the SVGs to PNG.
"""
import html
import pathlib

HERE = pathlib.Path(__file__).resolve().parent

THEMES = {
    'paper-and-ink': dict(
        name='Paper & Ink', room='#2a1f18', room_edge='#120d0a', paper='#f4ecdb', paper_edge='#e1d1b0',
        ink='#2b231c', muted='#6e6153', accent='#b08a4a', light='#ffd79a', light_op=0.55,
        red='#9c3a2a', green='#4c6b2f', yellow='#8a6a1c', blue='#2f5277', magenta='#7b3f6e', cyan='#2e6b6a',
        light_kind='carriage'),
    'midnight-study': dict(
        name='Midnight Study', room='#0d0a08', room_edge='#030202', paper='#1c1714', paper_edge='#2c241e',
        ink='#eadfc8', muted='#a39580', accent='#c9a45c', light='#ffb35c', light_op=0.32,
        red='#d2765c', green='#a3b46a', yellow='#e3b25c', blue='#7f9fc2', magenta='#c48aa8', cyan='#7fb3a8',
        light_kind='lamp'),
    'moonlit-poetry': dict(
        name='Moonlit Poetry', room='#0b0b14', room_edge='#040409', paper='#171826', paper_edge='#26283e',
        ink='#dcdcec', muted='#9496b4', accent='#b7bdd6', light='#cdd6ff', light_op=0.22,
        red='#d88a9a', green='#9cc3a4', yellow='#e2cf9a', blue='#8ea8e0', magenta='#b79ce0', cyan='#8cc8d6',
        light_kind='moon'),
}

MONO = "'IBM Plex Mono', 'DejaVu Sans Mono', Menlo, monospace"
SERIF = "'EB Garamond', 'Cormorant Garamond', Georgia, 'DejaVu Serif', serif"


def light_layer(t):
    if t['light_kind'] == 'carriage':
        return f'''<path d="M452 516 L508 516 L690 120 L270 120 Z" fill="url(#beam)"/>
    <ellipse cx="480" cy="520" rx="200" ry="70" fill="url(#pool)"/>'''
    if t['light_kind'] == 'lamp':
        return '''<ellipse cx="700" cy="150" rx="430" ry="300" fill="url(#pool)"/>'''
    return '''<path d="M120 60 L380 60 L760 560 L360 560 Z" fill="url(#beam)" opacity="0.8"/>
    <g fill="#e6e8ff" fill-opacity="0.5"><circle cx="300" cy="200" r="1.6"/><circle cx="420" cy="320" r="1.2"/>
    <circle cx="520" cy="250" r="1.4"/><circle cx="610" cy="430" r="1.1"/><circle cx="360" cy="400" r="1.3"/></g>'''


def svg(t):
    lines = [
        (f'<tspan fill="{t["accent"]}">~/manuscripts</tspan> <tspan fill="{t["muted"]}">on</tspan> '
         f'<tspan fill="{t["magenta"]}">main</tspan>'),
        f'<tspan fill="{t["ink"]}">$ git status --short</tspan>',
        f'<tspan fill="{t["green"]}"> M</tspan><tspan fill="{t["ink"]}"> chapter-01.md</tspan>',
        f'<tspan fill="{t["red"]}">??</tspan><tspan fill="{t["ink"]}"> sonnet-18.txt</tspan>',
        f'<tspan fill="{t["ink"]}">$ python3 -c "print(\'shall I compare thee\')"</tspan>',
        f'<tspan fill="{t["ink"]}">shall I compare thee</tspan>',
        f'<tspan fill="{t["ink"]}">$ ls</tspan>',
        (f'<tspan fill="{t["blue"]}">drafts/</tspan>  <tspan fill="{t["cyan"]}">notes.md</tspan>  '
         f'<tspan fill="{t["yellow"]}">纸与墨.txt</tspan>'),
        f'<tspan fill="{t["ink"]}">$ </tspan><tspan fill="{t["ink"]}">▍</tspan>',
    ]
    text = '\n      '.join(
        f'<text x="128" y="{170 + i * 34}">{line}</text>' for i, line in enumerate(lines))
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Typewriter Nocturne theme thumbnail: {html.escape(t["name"])}. Original artwork (MIT), generated by make_thumbnails.py -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 960 600" width="960" height="600">
  <defs>
    <radialGradient id="room" cx="55%" cy="35%" r="80%">
      <stop offset="0" stop-color="{t["room"]}"/>
      <stop offset="1" stop-color="{t["room_edge"]}"/>
    </radialGradient>
    <linearGradient id="beam" x1="0" y1="1" x2="0" y2="0">
      <stop offset="0" stop-color="{t["light"]}" stop-opacity="{t["light_op"]}"/>
      <stop offset="1" stop-color="{t["light"]}" stop-opacity="0"/>
    </linearGradient>
    <radialGradient id="pool" cx="50%" cy="50%" r="50%">
      <stop offset="0" stop-color="{t["light"]}" stop-opacity="{t["light_op"]}"/>
      <stop offset="1" stop-color="{t["light"]}" stop-opacity="0"/>
    </radialGradient>
    <filter id="shadow" x="-10%" y="-10%" width="120%" height="130%">
      <feGaussianBlur stdDeviation="14"/>
    </filter>
    <clipPath id="sheet"><rect x="96" y="96" width="768" height="440" rx="10"/></clipPath>
  </defs>
  <rect width="960" height="600" rx="18" fill="url(#room)"/>
  <!-- toolbar -->
  <circle cx="34" cy="30" r="7" fill="#d9614e"/><circle cx="58" cy="30" r="7" fill="#e0b04a"/>
  <circle cx="82" cy="30" r="7" fill="#79a85a"/>
  <text x="480" y="36" text-anchor="middle" font-family="{SERIF}" font-size="17" letter-spacing="3"
    fill="{t["accent"]}">TYPEWRITER NOCTURNE · {html.escape(t["name"].upper())}</text>
  <line x1="300" y1="56" x2="660" y2="56" stroke="{t["accent"]}" stroke-opacity="0.35"/>
  <!-- paper -->
  <rect x="104" y="108" width="768" height="440" rx="10" fill="#000" fill-opacity="0.5" filter="url(#shadow)"/>
  <rect x="96" y="96" width="768" height="440" rx="10" fill="{t["paper"]}" stroke="{t["paper_edge"]}"/>
  <g clip-path="url(#sheet)">
    {light_layer(t)}
    <g font-family="{MONO}" font-size="19">
      {text}
    </g>
  </g>
  <!-- status bar -->
  <text x="96" y="574" font-family="{SERIF}" font-size="15" font-style="italic" fill="{t["muted"]}">Chapter I — zsh</text>
  <text x="864" y="574" text-anchor="end" font-family="{MONO}" font-size="13" fill="{t["muted"]}">80 × 24 · UTF-8</text>
</svg>
'''


for slug, theme in THEMES.items():
    (HERE / f'{slug}.svg').write_text(svg(theme), encoding='utf-8')
    print('wrote', slug)
